import type { Metadata } from "next";
import { cookies } from "next/headers";
import { Suspense } from "react";
import { Geist, Geist_Mono, Inter } from "next/font/google";
import "./globals.css";
import { cn } from "@/lib/utils";
import { ThemeProvider } from "@/components/theme-provider";
import { SidebarProvider, SidebarTrigger } from "@/components/ui/sidebar";
import { MenuSidebar } from "@/components/menu-sidebar";

const inter = Inter({subsets:['latin'],variable:'--font-sans'});

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

interface CurrentUser {
  id: string;
  username: string;
  tenantId: string | null;
  tenantName: string | null;
  role: "SUBMITTER" | "AUDITOR" | "SYSTEM_ADMIN";
}

async function fetchCurrentUser(): Promise<CurrentUser | null> {
  const cookieStore = await cookies();
  const response = await fetch(new URL('/api/me', process.env.API_URL ?? 'http://localhost:4000'), {
    headers: { cookie: cookieStore.toString() },
    cache: 'no-store',
  });

  if (response.status === 401) {
    return null;
  }

  if (!response.ok) {
    throw new Error('Unable to load your account');
  }

  return response.json();
}

async function AccountLayout({ children }: { children: React.ReactNode }) {
  const userData = await fetchCurrentUser();

  if (!userData) return children;

  return (
    <SidebarProvider>
      <MenuSidebar tenantName={userData.tenantName ?? 'Unknown'} tenantRole={userData.role} username={userData.username} />
      <div className="flex min-w-0 flex-1 flex-col">
        <header className="flex h-12 shrink-0 items-center border-b px-4">
          <SidebarTrigger />
        </header>
        {children}
      </div>
    </SidebarProvider>
  );
}

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={cn("h-full", "antialiased", geistSans.variable, geistMono.variable, "font-sans", inter.variable)}
      suppressHydrationWarning
    >
      <body className="min-h-full flex flex-col">
        <ThemeProvider
          attribute="class"
          defaultTheme="system"
          enableSystem={true}
        >
          <Suspense fallback={<p role="status" className="p-4 text-sm text-muted-foreground">Loading account…</p>}>
            <AccountLayout>{children}</AccountLayout>
          </Suspense>
        </ThemeProvider>
      </body>
    </html>
  );
}
